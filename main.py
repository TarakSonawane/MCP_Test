@app.post("/tools/update-fnol", operation_id="update_fnol", tags=["tools"],
          summary="Record FNOL answers in any order. Returns the draft, issues and escalations")
def tool_update_fnol(req: UpdateFnolRequest):
    answers = req.model_dump(exclude={"session_id"}, exclude_none=True)
    unknown = sorted(set(answers) - ANSWER_FIELDS)
    if unknown:
        raise HTTPException(status_code=400, detail={"error": f"Unknown fields: {unknown}"})
    return finish(update_fnol(req.session_id, **answers))


