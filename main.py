def _examples() -> dict:
    """Compact view of the Illinois seed so a caller can pick a demo without listing PII dumps."""
    customers = []
    for customer in stores.customers.list():
        party = customer.general_party_info
        person = customer.person_name
        addr = party.addr
        customers.append(
            {
                "customer_id": customer.customer_id,
                "given_name": person.given_name if person else None,
                "surname": person.surname if person else None,
                "birth_dt": (
                    customer.person_info.birth_dt.isoformat()
                    if customer.person_info.birth_dt
                    else None
                ),
                "email": party.email_addr,
                "phone": party.phone_number,
                "city": addr.city if addr else None,
                "postal_code": addr.postal_code if addr else None,
                "addr_line1": addr.addr_line1 if addr else None,
                "policies": [
                    {"policy_number": role.policy_number, "role": role.policy_role_cd.value}
                    for role in customer.policy_roles
                ],
            }
        )

    policies = []
    for policy in stores.policies.list():
        policies.append(
            {
                "policy_number": policy.policy_number,
                "status": policy.policy_status_cd.value,
                "lob_cd": policy.lob_cd.value,
                "producer_cd": policy.producer_cd,
                "vehicles": [
                    {
                        "veh_seq_num": veh.veh_seq_num,
                        "year": veh.model_year,
                        "make": veh.manufacturer,
                        "model": veh.model,
                        "vin": veh.vin,
                        "plate": veh.license_plate,
                        "plate_state": veh.state_prov_cd,
                    }
                    for veh in policy.pers_veh
                ],
                "drivers": [
                    {
                        "given_name": drv.person_name.given_name,
                        "surname": drv.person_name.surname,
                        "relationship": drv.driver_relationship_cd.value,
                    }
                    for drv in policy.pers_driver
                ],
            }
        )

    claims = []
    for claim in stores.claims.list():
        claims.append(
            {
                "session_id": claim.session_id,
                "claim_id": claim.claim_id,
                "claim_number": claim.claim_number,
                "status": claim.status.value,
                "customer_id": claim.customer_id,
                "policy_number": claim.policy.policy_number if claim.policy else None,
                "claim_type_cd": (
                    claim.claims_occurrence.claim_type_cd.value
                    if claim.claims_occurrence.claim_type_cd
                    else None
                ),
                "verified": claim.authentication.verified_ind,
                "open_escalations": len(claim.open_escalations),
            }
        )

    return {
        "note": (
            "In-memory Illinois demo. Dates stay relative to today. "
            "Happy path: Jane Doe, POL-PC-001, birth_dt 1988-04-12, "
            "email jane.doe@example.com, Honda Accord plate JDOE21. "
            "Partial draft already on file: sess-seed-0008."
        ),
        "counts": stores.counts(),
        "customers": customers,
        "policies": policies,
        "claims": claims,
        "reference_lists": sorted(REFERENCE_LISTS),
    }


